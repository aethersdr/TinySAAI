#!/usr/bin/env python3
"""Generate ai/COVERAGE.md from what the instrument reports.

    python3 ai/make_coverage.py ANALYZER_DUMP GENERATOR_TREE ai/commands-upstream.txt > ai/COVERAGE.md

ANALYZER_DUMP: the console replies to `ui tree` then `param`, in analyzer mode,
separated by a line '### param'. GENERATOR_TREE: the reply to `ui tree` in low
output mode (output off). commands-upstream.txt: name, flags and usage text of
each upstream console command, from the source.
"""
import collections
import sys

MEASUREMENTS = [
    ("off", "-"),
    ("harmonic", "fundamental frequency; span (0 = full span)"),
    ("oip3", "left signal frequency; right signal frequency"),
    ("phase_noise", "signal frequency; frequency offset"),
    ("snr", "signal frequency; bandwidth"),
    ("pass_band", "- (-3 dB width around the peak)"),
    ("occupied_width", "dBc level, e.g. -20"),
    ("am", "signal frequency; modulation frequency"),
    ("fm", "signal frequency; modulation frequency; deviation"),
    ("thd", "-"),
    ("channel_power", "channel frequency; channel width"),
    ("nf_tinysa", "noise center frequency (input terminated in 50 ohm)"),
    ("nf_store", "- ; saves the noise figure: needs confirm"),
    ("nf_validate", "-"),
    ("nf_amplifier", "amplifier gain"),
    ("linearity", "- (low input mode)"),
]


def esc(s):
    return s.replace("|", "\\|")


def kinds(rows):
    c = collections.Counter(r[1] for r in rows)
    return ", ".join("%d %s" % (c[k], k) for k in ("setting", "value", "action", "menu", "title", "back") if c[k])


def rows(text):
    return [(l.split("|") + [""] * 5)[:5] for l in text.strip().splitlines() if l.strip()]


def main(dump_path, gen_path, syntax_path):
    analyzer, params = open(dump_path).read().split("### param\n")
    tree, gen = rows(analyzer), rows(open(gen_path).read())
    params = [(l.split("|") + ["", "", ""])[:3] for l in params.strip().splitlines() if l.strip()]
    syn = [(l.split(None, 2) + ["", "", ""])[:3] for l in open(syntax_path).read().splitlines() if l.strip()]
    added = [("calibrate", "0", "calibrate: level calibration from the console, prints the outcome"),
             ("state", "0", "state: every setting as key value lines"),
             ("ui", "1", "ui [ls [key] | tree | get <key>]; ui <key> [values...] [confirm]"),
             ("param", "1", "param [name [value [confirm]]]"),
             ("measure", "1", "measure [name [values...] [confirm]]"),
             ("readout", "1", "readout: marker and measurement text as on screen"),
             ("band", "1", "band [n [off]]: list, select and enable, or disable a band"),
             ("limit", "1", "limit [n [off]]: the same for the selected trace's limit lines")]
    out = []
    P = out.append
    P("# TinySAAI coverage\n")
    P("What a software agent can set and read on a tinySA Ultra+ (ZS407, hardware V0.5.4) running "
      "TinySAAI, generated by `ai/make_coverage.py` from the instrument's own replies: `ui tree` in "
      "analyzer mode and in low-output (generator) mode, and `param`. Upstream base `ab5ecd5` "
      "(tinySA4 v1.4-302).\n")
    P("## Summary\n")
    P("| Surface | How an agent reaches it | Count |")
    P("|---|---|---|")
    P("| Analyzer menus | `ui ls`, `ui get <key>` read; `ui <key> [values] [confirm]` press | %d items (%s) |" % (len(tree), kinds(tree)))
    P("| Generator menus (low output) | the same, rooted at the generator menu | %d items (%s) |" % (len(gen), kinds(gen)))
    P("| Numeric parameters | `param [name [value [confirm]]]` | %d (%d write the stored configuration) |"
      % (len(params), sum(1 for p in params if p[1] == "config")))
    P("| Measurements | `measure <name> [values]`, `waitscan 2`, `readout` | %d modes; 15 set up and read on the unit (`nf_store` not run: it saves to flash) |" % len(MEASUREMENTS))
    P("| Readings | `readout` (marker and measurement text as on screen), `marker`, `scan`, `data`, `channel` | all modes |")
    P("| Settings summary | `state` | one line per setting |")
    P("| Level calibration | `calibrate` | blocking, prints the outcome |")
    P("| Self test | `selftest report` | blocking, prints every step's result |")
    P("| Bands and limit lines | `band`, `limit` | 8 bands; 8 limits per trace |")
    P("| Console commands | named commands, last table | %d |\n" % (len(syn) + 6))
    P("## What is not reachable from the console\n")
    P("Refused by `ui` because they wait for a person at the screen, cut the USB console, or erase the "
      "configuration (`state` column `refused`):\n")
    seen = set()
    for r in tree:
        if r[2] == "refused" and r[0] not in seen:
            seen.add(r[0])
            P("- `%s`: %s" % (r[0], esc(r[4])))
    P("\nNot built, or not listed by `ui tree`:\n")
    P("- The menu level calibration (both CALIBRATE items): use the `calibrate` command. The calibration "
      "above 5.34/7.37 GHz, which needs an external signal, has no console equivalent yet.")
    P("- The band and limit menus (MULTI BAND, the trace TABLE items) are not listed by `ui tree`, "
      "because their screens enable a band or limit while they are drawn. Use `band` and `limit` "
      "instead: list, select and enable, or disable an entry; then `param band_*` or `param limit_*`.")
    P("- Loading from the SD card (file browser), the curve editor (reached only through the guarded IN/OUT "
      "CURVE items), and brightness (adjusted with the jog wheel).")
    P("- INTERNALS asks for code 5432 the first time after power-up: "
      "`ui config.more.expert_config.internals.<item> 5432 [values]`; later presses need no code.\n")
    P("## Guarded items\n")
    P("These change the stored configuration, calibration or synthesizer setup, and need a trailing "
      "`confirm` (`state` column `confirm`). `param` names of class `config` and `measure nf_store` too.\n")
    for r in tree:
        if r[2] == "confirm":
            P("- `%s`: %s" % (r[0], esc(r[4])))
    P("\n## Measurements\n")
    P("A prompt left without a value is reported by its text, and the measurement is switched off; "
      "settings its setup had already changed (center, span, RBW, markers) stay changed. Readings are "
      "valid after a complete sweep: `waitscan 2` before `readout`.\n")
    P("| `measure` name | Values, in prompt order |")
    P("|---|---|")
    for n, v in MEASUREMENTS:
        P("| `%s` | %s |" % (n, v))
    for title, rs in (("Analyzer menu tree", tree), ("Generator menu tree (low output)", gen)):
        P("\n## %s\n" % title)
        P("| Key | Kind | State | Value | Label |")
        P("|---|---|---|---|---|")
        for r in rs:
            P("| `%s` | %s | %s | %s | %s |" % (r[0], r[1], r[2], esc(r[3]), esc(r[4])))
    P("\n## Numeric parameters\n")
    P("| Name | Class | Value when generated |")
    P("|---|---|---|")
    for p in params:
        P("| `%s` | %s | %s |" % (p[0], p[1], esc(p[2])))
    P("\n## Console commands\n")
    P("Flags: 1 runs in the sweep thread, 2 allowed in load scripts, 4 may run while a screen waits, "
      "8 allowed in USB-disk mode. Usage is the text in the source. Single letters are the upstream "
      "remote-control set.\n")
    P("| Command | Flags | Usage |")
    P("|---|---|---|")
    names = {s[0] for s in syn}
    for s in syn + [a for a in added if a[0] not in names]:
        P("| `%s` | %s | %s |" % (s[0], s[1], esc(s[2]).strip()))
    print("\n".join(out))


if __name__ == "__main__":
    main(*sys.argv[1:4])
